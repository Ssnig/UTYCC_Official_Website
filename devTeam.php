            <h1>About This Website</h1>
            <p>
                We are students who gained
                admission to the University of
                Technology (Yadanarpon
                Cyber City) for the 12th intake
                (Academic Year 2022-2023)As students majoring in
                Information Science and
                Technology, we undertook a
                group project during the
                second semester of our third
                year (Academic Year 2024-
                2025) to develop a website
                that could be used by admitted
                (new) students and current
                students of the University for
                registration.
                As this was a group project,
                the selection of the group
                leader and the designation of
                group members were carried
                out by the third-year students,
                ourselves, on August 1, 2025.
                The team collaborated on fundamental tasks such as
                requesting the registration form
                and necessary documents
                from the Student Affairs Office,
                with each member taking
                ownership of specific
                responsibilities they could
                handle, and setting deadlines
                for those tasks. Furthermore, the group
                members repeatedly convened
                during breaks in class and on
                holidays to prepare and
                supplement the website
                requirements, conduct testing,
                detect errors, and correct them
                together.
                On September 12, 2025, we
                presented and discussed our
                registration project in front of
                the University Registrar, as
                well as Professors and
                Lecturers from the Department
                of Information Science and
                Technology.
                Within the short span of only
                43 days, we exerted our best
                efforts, combining our skills
                and intellect. The outcome of
                that effort was further refined
                and supplemented, allowing us
                to create a website that can
                now be utilized not only by the
                University's students but also
                by prospective students
                interested in learning more
